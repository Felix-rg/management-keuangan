"""Database schema for Keuangan Mandiri. All money is stored as integer rupiah."""
from datetime import datetime, date, timezone
from sqlalchemy import BigInteger, Boolean, Date, DateTime, ForeignKey, Integer, String, Text, UniqueConstraint
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

class Base(DeclarativeBase):
    pass

def utcnow():
    return datetime.now(timezone.utc).replace(tzinfo=None)

class Account(Base):
    __tablename__ = 'accounts'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    name: Mapped[str] = mapped_column(String(90), unique=True)
    kind: Mapped[str] = mapped_column(String(25), default='cash')
    opening_balance: Mapped[int] = mapped_column(BigInteger, default=0)
    archived: Mapped[bool] = mapped_column(Boolean, default=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)

class Category(Base):
    __tablename__ = 'categories'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    name: Mapped[str] = mapped_column(String(70))
    kind: Mapped[str] = mapped_column(String(10))
    archived: Mapped[bool] = mapped_column(Boolean, default=False)
    __table_args__ = (UniqueConstraint('name', 'kind', name='uq_category_name_kind'),)

class Transaction(Base):
    __tablename__ = 'transactions'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    tx_date: Mapped[date] = mapped_column(Date, index=True)
    kind: Mapped[str] = mapped_column(String(12), index=True)
    amount: Mapped[int] = mapped_column(BigInteger)
    account_id: Mapped[int] = mapped_column(ForeignKey('accounts.id', ondelete='RESTRICT'))
    to_account_id: Mapped[int | None] = mapped_column(ForeignKey('accounts.id', ondelete='RESTRICT'))
    category_id: Mapped[int | None] = mapped_column(ForeignKey('categories.id', ondelete='RESTRICT'))
    note: Mapped[str] = mapped_column(Text, default='')
    payment_id: Mapped[int | None] = mapped_column(Integer, index=True)  # non-null => generated by debt repayment
    recurring_id: Mapped[int | None] = mapped_column(Integer, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)
    __table_args__ = (UniqueConstraint('recurring_id', 'tx_date', name='uq_recurring_one_per_date'),)

class Budget(Base):
    __tablename__ = 'budgets'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    category_id: Mapped[int] = mapped_column(ForeignKey('categories.id', ondelete='RESTRICT'))
    month: Mapped[str] = mapped_column(String(7), index=True)
    amount: Mapped[int] = mapped_column(BigInteger)
    __table_args__ = (UniqueConstraint('category_id', 'month', name='uq_budget_category_month'),)

class Goal(Base):
    __tablename__ = 'goals'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    name: Mapped[str] = mapped_column(String(100))
    target: Mapped[int] = mapped_column(BigInteger)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)

class GoalDeposit(Base):
    __tablename__ = 'goal_deposits'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    goal_id: Mapped[int] = mapped_column(ForeignKey('goals.id', ondelete='CASCADE'))
    amount: Mapped[int] = mapped_column(BigInteger)
    deposit_date: Mapped[date] = mapped_column(Date)
    note: Mapped[str] = mapped_column(String(240), default='')

class Debt(Base):
    __tablename__ = 'debts'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    kind: Mapped[str] = mapped_column(String(12))  # debt / receivable
    person: Mapped[str] = mapped_column(String(110))
    amount: Mapped[int] = mapped_column(BigInteger)
    due_date: Mapped[date | None] = mapped_column(Date)
    note: Mapped[str] = mapped_column(Text, default='')
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)

class DebtPayment(Base):
    __tablename__ = 'debt_payments'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    debt_id: Mapped[int] = mapped_column(ForeignKey('debts.id', ondelete='CASCADE'))
    account_id: Mapped[int] = mapped_column(ForeignKey('accounts.id', ondelete='RESTRICT'))
    amount: Mapped[int] = mapped_column(BigInteger)
    paid_date: Mapped[date] = mapped_column(Date)
    transaction_id: Mapped[int | None] = mapped_column(Integer)

class Recurring(Base):
    __tablename__ = 'recurring'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    kind: Mapped[str] = mapped_column(String(12))
    amount: Mapped[int] = mapped_column(BigInteger)
    account_id: Mapped[int] = mapped_column(ForeignKey('accounts.id', ondelete='RESTRICT'))
    to_account_id: Mapped[int | None] = mapped_column(ForeignKey('accounts.id', ondelete='RESTRICT'))
    category_id: Mapped[int | None] = mapped_column(ForeignKey('categories.id', ondelete='RESTRICT'))
    interval: Mapped[str] = mapped_column(String(10))
    next_date: Mapped[date] = mapped_column(Date)
    note: Mapped[str] = mapped_column(String(240), default='')
    active: Mapped[bool] = mapped_column(Boolean, default=True)

class LoginAttempt(Base):
    __tablename__ = 'login_attempts'
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    ip_hash: Mapped[str] = mapped_column(String(64), index=True)
    at: Mapped[datetime] = mapped_column(DateTime, default=utcnow, index=True)
